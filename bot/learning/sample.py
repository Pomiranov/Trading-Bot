"""Обучающая выборка: ОДИН предикат для всех потребителей (долг №30).

Зачем модуль на одну константу. Мест `FROM trades` в проекте 25 в 20 файлах, и
скопированный по ним фильтр разъехался бы так же, как три копии ставки 0.0003 и
семь копий пути к правилам. Поэтому предикат объявлен здесь, а потребители его
импортируют.

Фильтруются НЕ все 25 мест, а только обучающая выборка: belief_updater,
hypothesis_engine и статистические выборки learning-пути. UI, дашборд, портфель и
статистика показывают сделки человеку — скрывать от него историю не нужно, и
там предикат сознательно НЕ применяется.

Два условия, и оба необходимы:

1. `rules_version` известен. До 2026-07-28 сделки не привязывались к набору
   правил вообще, и 7 532 строки помечены 'unknown' задним числом. Обычной
   строкой, а не NULL: NULL в сравнениях ведёт себя иначе, и `<> 'unknown'`
   пропустил бы его молча — поэтому проверяются оба случая.

2. `origin` — форвард или живой контур. Одного отпечатка НЕ достаточно: после
   введения отпечатков бэктестовые прогоны начали писать ВАЛИДНЫЙ хеш, и
   run_ab_tf_backtest с run_ab_backtest дали бы 10 179 строк, проходящих фильтр
   как полноправная обучающая выборка (`run_ab_backtest.py` удалён 30.07 как
   перекрытый `run_ab_tf_backtest --learn`; довод от этого не слабеет — писать
   валидный хеш умеет любой бэктестовый прогон). `is_sandbox` различителем не
   является — он про бумагу против реальных денег, и форвард тоже
   `is_sandbox = true` (проверено: у всех 7 532 строк `is_sandbox = true`, ни
   одной false или NULL).

ЧЕГО ЗДЕСЬ НЕТ И ПОЧЕМУ ЭТО ВАЖНО: условия `closed_at IS NOT NULL`. Предикат
отбирает выборку по ПРОИСХОЖДЕНИЮ, а не по завершённости, и закрытость каждый
потребитель дописывает сам (belief_updater.py:103,339,
hypothesis_engine.py:100,134,170,305). После долга №25 у бэктеста появились
строки с `closed_at IS NULL` — позиции, открытые на краю данных и больше НЕ
закрываемые принудительно. Замерено 30.07 транзакцией с откатом: строка с
`closed_at IS NULL`, `origin='forward'` и валидным `rules_version` проходит
TRAINING_SAMPLE_SQL целиком и всё равно не попадает в обучающую выборку — 0 → 0.
То есть барьер работает, но он ОДИН и живёт у потребителей. Новый потребитель,
забывший его дописать, получит незавершённые сделки молча.
"""

# SQL-фрагмент, а не готовый запрос: потребители комбинируют его со своими
# условиями через AND. Значений извне здесь нет — только литералы, поэтому
# подстановка в текст запроса безопасна.
TRAINING_SAMPLE_SQL = (
    "rules_version IS NOT NULL "
    "AND rules_version <> 'unknown' "
    "AND origin IN ('forward', 'live')"
)

# Метка для строк, записанных до введения отпечатка. Дублирует
# signals.rules_engine.RULES_VERSION_UNKNOWN намеренно: learning-путь не должен
# импортировать движок правил ради одной строки. Значения обязаны совпадать —
# это проверяется тестом.
RULES_VERSION_UNKNOWN = "unknown"
