# ── БАРОВ НА СЕССИЮ: множитель ПРИКОЛОЧЕН, НЕ считается на ходу ──────────────
#
# Долг №50, вариант E2 (решение человека 03.08) с поправкой того же дня: окна
# задаются в СЕССИЯХ, а движок переводит их в бары таймфрейма умножением на этот
# множитель. Поправка — в том, что множитель ПРИКОЛОЧЕН константой, а не считается
# из данных.
#
# 🚫 АВТОРАСЧЁТ ИЗ ДАННЫХ ЗАПРЕЩЁН, и это не вкусовщина. Замер по `candles`:
# у 4h 3 743 бара на бумагу при 870 сессиях, среднее 4.3, но распределение
# min 2 … max 5. Считаемое на ходу число молча менялось бы при каждой догрузке
# (класс долга №37: параметр измерения не приколочен) и разошлось бы с
# пре-регистрацией `EXPERIMENTS.md`, где все 17 значений уже названы. Приколоченный
# множитель делает 17 чисел воспроизводимыми через полгода; считаемый — нет.
#
# ⚠ ХРАНИТСЯ ДРОБЬЮ, А НЕ ЧИСЛОМ С ТОЧКОЙ, и это тоже замер, а не стиль.
# `pivot_max_age = 25` — ЕДИНСТВЕННЫЙ из семнадцати параметров на границе `.5`:
#     дробью и целыми: (25·43 + 5) // 10 = 1080 // 10 = 108   ← пре-регистрация
#     через float:      25 * 4.3 = 107.49999999999999 → 107    ← НЕВЕРНО
# Остальные шестнадцать далеко от `.5` и правильны при любом способе, поэтому
# дефект был бы невидим на 16 из 17. Класс: «число, верное на бумаге и неверное в
# машине».
BARS_PER_SESSION: dict[str, tuple[int, int]] = {
    "D1": (1, 1),        # по определению: один дневной бар на сессию
    "H4": (43, 10),      # 4.3 — замерено, не округлено (3 743 бара / 870 сессий)
    "H1": (156, 10),     # 15.6 — тем же замером
}


def bars_per_session_version(table: dict[str, tuple[int, int]]) -> str:
    """Отпечаток таблицы множителей: sha256[:16], идиома `universe_version`.

    Своё пространство имён, как у `sample_version`: без префикса отпечаток
    таблицы из одной записи совпал бы с отпечатком набора из одного тикера —
    ровно та ловушка, которую тест нашёл 30.07.
    """
    payload = "bars_per_session:" + ",".join(
        f"{tf}={num}/{den}" for tf, (num, den) in sorted(table.items()))
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()[:16]


BARS_PER_SESSION_VERSION = bars_per_session_version(BARS_PER_SESSION)


def scale_sessions_to_bars(sessions: int, timeframe: str) -> int:
    """Окно, заданное в СЕССИЯХ, → бары таймфрейма. Половина ВВЕРХ, целыми.

    Округление названо словами намеренно: «половина вверх» есть решение, а не
    свойство языка. `round()` в Python округляет половину К ЧЁТНОМУ
    (`round(107.5) == 108`, но `round(106.5) == 106`), то есть при том же
    множителе давал бы разные правила для разных окон.

    ⚠ ОБЛАСТЬ ПРИМЕНЕНИЯ — ПРЕДИКАТОМ, не списком вызывающих: множитель
    применяется к окну, заданному в барах СЫРОГО таймфрейма, и НЕ применяется к
    окну, считаемому на РЕСЕМПЛЁННОМ дневном ряде. Окна фильтра даунтренда
    (`sma_long` 200 и соседи) считаются на ресемплённых дневных барах
    (`backtest/engine.py::_downtrend_gate`), их окна уже календарные, и умножение
    дало бы 200 × 4.3 = 860 дневных баров — двойной пересчёт.
    """
    if timeframe not in BARS_PER_SESSION:
        raise KeyError(
            f"таймфрейм {timeframe!r} не в BARS_PER_SESSION: множитель приколочен "
            f"и на ходу не считается, добавить его — решение человека"
        )
    num, den = BARS_PER_SESSION[timeframe]
    return (sessions * num + den // 2) // den


