FORWARD_TICKERS_PENDING_FIXED_AT = "2026-07-28"
FORWARD_TICKERS_PENDING_ENTERS_AT = "2026-07-29"


def universe_version(tickers: tuple[str, ...]) -> str:
    """Отпечаток набора: sha256[:16] от отсортированного списка через запятую.

    Тот же приём, что RulesEngine.rules_version. Печатается каждым прогоном:
    отчёт без версии набора через полгода нечитаем — по нему нельзя сказать, на
    каких бумагах он посчитан.
    """
    payload = ",".join(sorted(tickers))
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()[:16]


MEASUREMENT_UNIVERSE_2026_07_VERSION = universe_version(MEASUREMENT_UNIVERSE_2026_07)
MEASUREMENT_UNIVERSE_2026_07_EXT_VERSION = universe_version(MEASUREMENT_UNIVERSE_2026_07_EXT)
FORWARD_TICKERS_VERSION = universe_version(FORWARD_TICKERS)
FORWARD_TICKERS_PENDING_VERSION = universe_version(FORWARD_TICKERS_PENDING)


def describe(name: str, tickers: tuple[str, ...]) -> str:
    """Строка для шапки прогона: имя набора, размер, отпечаток."""
    return f"{name}: {len(tickers)} бумаг, отпечаток {universe_version(tickers)}"
