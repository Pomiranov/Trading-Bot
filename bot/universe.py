def universe_version(tickers: tuple[str, ...]) -> str:
    """Отпечаток набора: sha256[:16] от отсортированного списка через запятую.

    Тот же приём, что RulesEngine.rules_version. Печатается каждым прогоном:
    отчёт без версии набора через полгода нечитаем — по нему нельзя сказать, на
    каких бумагах он посчитан.
    """
    payload = ",".join(sorted(tickers))
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()[:16]


