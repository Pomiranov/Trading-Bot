"""Расписание прогонов форварда: слоты, льготный интервал, путь журнала.

ОДНО место на весь проект. Причина не в аккуратности: до 01.08 время «00:15»
существовало только внутри планировщика Windows, и сторож о нём не знал вовсе —
он выводил пропуск прогона из возраста бара. Если бы он захардкодил своё «00:15»,
появились бы ДВЕ копии одного факта, и при переносе слота сторож начал бы врать
молча. Это класс «список вместо предиката» (правило 8 §8).

Поэтому связь с планировщиком проверяется машинно, двумя звеньями:

  константа здесь  ←→  закоммиченный экспорт XML  ←→  живая задача Windows
       tests/forward_tests/test_forward_run_journal.py   tools/check_scheduled_tasks.py

Третьей копии не появляется: перенесли слот — падает либо тест, либо проверка.

Импорт-бюджет: ТОЛЬКО stdlib, по образцу market_time.py. Модуль зовут и сторож
(у него узкий бюджет: он не должен зависеть от того, что охраняет), и
run_journal.py, который пишет первую строку прогона раньше подключения к БД.
"""

