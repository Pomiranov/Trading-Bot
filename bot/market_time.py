"""Конвенция времени баров MOEX. Единственный источник для ВСЕХ контуров.

Модуль сознательно без импортов из проекта (ни config, ни БД): от конвенции
времени зависят и форвард, и бэктест, и если она разъедется между ними,
сравнение контуров начнёт мерить конвенцию, а не правила. Ровно это и
произошло с частичным баром — см. last_closed_index.
"""

from datetime import datetime, timedelta, timezone

# В РФ нет перехода на летнее время с 2014 — фиксированный сдвиг вместо
# ZoneInfo, чтобы не зависеть от наличия tzdata на сервере.
MSK = timezone(timedelta(hours=3))


def last_closed_index(raw_times: list) -> int:
    """Индекс последнего ЗАКРЫТОГО бара: сегодняшняя сессия ещё формируется.

    raw_times — tz-aware метки в хронологическом порядке. −1 = закрытых баров
    нет вообще.

    ФОРВАРД (исходный повод, долг №14). В 00:15 МСК (штатное расписание)
    поведение не меняется. Но прогон бывает внеурочным — реальный случай 11:41
    после пропущенного триггера при StartWhenAvailable=True — и тогда ISS
    отдаёт ЧАСТИЧНЫЙ бар за сегодня. С побарным продвижением состояния он стал
    бы last_candle_time, а когда следующий прогон заменит строку завершённым
    OHLC (DELETE+INSERT в data/loader.py), завершённый бар был бы перешагнут
    навсегда.

    БЭКТЕСТ (2026-07-28). Тот же частичный бар попадал последним в серию, и на
    нём движок принудительно закрывал открытую позицию (backtest/engine.py:315),
    то есть записывал в n/WR/PF/PnL сделку, оценённую по НЕЗАКРЫТОЙ сессии.
    Измерено на osc_range D1 без фильтра даунтренда: одна такая сделка (SBER,
    вход 24.07) давала +20 460 руб. и сдвигала OOS PF 1.16 → 1.22, n 29 → 30.
    Пока функция жила только в форварде, контуры расходились на этом баре —
    ровно тот перекос, который сравнение форвард↔бэктест призвано исключать.

    Отдельно от этого остаётся долг: принудительное закрытие на последнем баре
    учитывается как обычная сделка и тогда, когда последний бар закрыт. Здесь
    оно не лечится — обрезается только незакрытый бар.
    """
    today = datetime.now(MSK).date()
    for i in range(len(raw_times) - 1, -1, -1):
        if raw_times[i].astimezone(MSK).date() < today:
            return i
    return -1
