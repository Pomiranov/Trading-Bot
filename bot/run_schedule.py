# ── Льготный интервал «прогон ещё идёт» ──────────────────────────────────────
#
# Зачем он вообще нужен. Без него состояние «есть старт, финиша нет» читается
# как «прогон умер», и это ЛОЖНАЯ тревога на каждой догнанной ночи: замерено
# 01.08, что при догоне после сна планировщик запускает форвард и сторожа ОДНОЙ
# секундой — форвард стартовал 11:38:44, сторож отработал 11:38:45, финиш
# прогона был только в 11:38:56. Сторож увидел бы собственный прогон мёртвым.
#
# Почему НЕ «типичная длительность прогона». Замер 01.08 по парам меток в
# logs/forward_d1.log дал по 9 полным прогонам медиану 5 с и максимум 31 с — но
# метки в этом логе начинаются с вывода db_wait.py, то есть ПОСЛЕ гейтов .bat.
# Ожидание docker-демона и БД в замер не входит, а §10(б) PROJECT_STATE
# замерил, что Docker Desktop после гибернации публикует порт МИНУТАМИ. Льгота
# в 31 с объявила бы мёртвым первый же прогон, законно ждущий Docker после сна.
#
# Поэтому интервал — СУММА бюджетов ожидания и длительности самого прогона:
DAEMON_WAIT_S = 180      # ВЗЯТО из run_forward_d1.bat (set DAEMON_WAIT_S)
DBWAIT_TIMEOUT = 450     # ВЗЯТО из run_forward_d1.bat (set DBWAIT_TIMEOUT)
RUN_MAX_SEC = 31         # ИЗМЕРЕНО: максимум по 9 полным прогонам, 12.07 18:31
RUN_SAFETY = 2           # ВЫБРАНО: запас на рост набора бумаг. Зависимость
                         # длительности от размера набора не линейна и НЕ
                         # замерена — 12 бумаг дали 31 с, 20 бумаг дали 12 с.

GRACE_SEC = DAEMON_WAIT_S + DBWAIT_TIMEOUT + RUN_MAX_SEC * RUN_SAFETY   # 692

# Допуск «старт относится к своему слоту, а не опоздал». Нужен, чтобы обычный
# разброс планировщика не читался как пропуск слота.
#
# ИЗМЕРЕНО 01.08 по logs/forward_d1.log: первая строка прогона появлялась через
# 4–13 с после слота (00:15:04, 00:15:06, 00:15:08, 00:15:13), причём это уже
# ПОСЛЕ гейтов .bat; сам запуск задачи — раньше. Разброс же, который ловим, —
# 11 ч 23 мин (прогон 01.08).
# ВЫБРАНО 120 с: на порядок выше наблюдаемого разброса и на два порядка ниже
# пропуска, который проверка обязана поймать. Между этими границами величина
# ни на что не влияет, поэтому точность здесь не покупается замером.
SLOT_TOLERANCE_SEC = 120

# Первые два слагаемых живут в .bat, и это ЕДИНСТВЕННЫЙ их источник: тест
# извлекает их регуляркой и сверяет с числами выше (образец —
# test_wait_budget_is_one_number в test_forward_start_gate.py). Ниже — та же
# регулярка, чтобы и тест, и человек читали .bat одинаково.
_BAT_BUDGET = re.compile(r"^\s*set\s+(DAEMON_WAIT_S|DBWAIT_TIMEOUT)\s*=\s*(\d+)\s*$",
                         re.MULTILINE | re.IGNORECASE)


def bat_budgets(bat_text: str) -> dict[str, int]:
    """Бюджеты ожидания, прочитанные из текста run_forward_d1.bat.

    Отдаётся наружу, а не остаётся в тесте: одна регулярка на проверку и на
    диагностику. Пустой словарь при отсутствии строк — fail-loud остаётся за
    вызывающим: молчаливый дефолт здесь означал бы «сверка прошла», когда
    сверять было нечего.
    """
    return {m.group(1).upper(): int(m.group(2)) for m in _BAT_BUDGET.finditer(bat_text)}


