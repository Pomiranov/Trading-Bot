# 🚫 НЕ РОТИРОВАТЬ И НЕ УСЕКАТЬ НИКОГДА. Две строки в сутки — около 70 КБ в год.
# Ротация вернула бы неразличимость «записи о старте нет» и «свидетельство
# утрачено», против которой введена строка journal_created (долг №46).
# Запрет записан и в infra/logrotate/quantflow.conf, и в долге №46.
JOURNAL_DEFAULT = "logs/forward_runs.jsonl"

# Переменная окружения — ради живой проверки НА КОПИИ. Боевой журнал
# append-only и правке руками не подлежит: отредактированный руками, он
# перестаёт быть свидетельством. Образец — контроль 30.07 на клоне БД
# forward_control, где боевые данные не трогались вовсе.
JOURNAL_ENV = "FWD_RUN_JOURNAL"


# Признак «этот процесс — прогон, запущенный ПО РАСПИСАНИЮ». Ставит его
# run_forward_d1.bat сразу после записи `start`, и только он.
#
# Заведено 01.08 по факту, найденному живой проверкой: replay-тесты
# (tests/forward_tests/test_forward_replay.py и соседи) поднимают ForwardRunner
# в процессе, дошли до записи `session` и налили 97 строк в БОЕВОЙ журнал —
# все `session`, ни одного `start`. Такая строка не просто мусор: сторож
# привязывает `session` к последнему предшествующему `start`, то есть чужая
# запись могла бы прицепиться к настоящему прогону и объявить обработанной
# сессию, которой прогон не видел.
#
# Предикат, а не память «не забыть переменную окружения в тестах»: писать
# `session` вправе ТОЛЬКО процесс, о старте которого .bat сделал запись.
IN_SLOT_RUN_ENV = "FWD_IN_SLOT_RUN"


def in_slot_run() -> bool:
    """Запущен ли этот процесс как прогон по расписанию (а не тест/бэктест)."""
    return bool(os.getenv(IN_SLOT_RUN_ENV))


def journal_path(root) -> str:
    """Путь журнала прогонов. Читается ПРИ ВЫЗОВЕ, не на импорте.

    На импорте его читать нельзя: тест меняет переменную окружения между
    случаями, а модуль к тому моменту уже импортирован сторожем.
    """
    override = os.getenv(JOURNAL_ENV)
    if override:
        return override
    return str(root).rstrip("\\/") + "/" + JOURNAL_DEFAULT


# ── Какой слот считается ожидаемым ───────────────────────────────────────────


def last_slot(now: datetime, slot: dtime = SLOT_FORWARD) -> datetime:
    """Последний ПРОШЕДШИЙ слот на момент now (tz-aware, МСК).

    Именно «прошедший», а не «сегодняшний»: сторож в 09:00 проверяет слот 00:15
    того же дня, а сторож, догнанный в 11:38, — тот же слот. Но сторож,
    запущенный вручную в 00:05, обязан спрашивать про ВЧЕРАШНИЙ слот, иначе
    потребует записи о прогоне, который ещё не должен был случиться.
    """
    now_msk = now.astimezone(MSK)
    today_slot = datetime.combine(now_msk.date(), slot, tzinfo=MSK)
    if now_msk >= today_slot:
        return today_slot
    return today_slot - timedelta(days=1)


def slot_session(slot_at: datetime) -> date:
    """Московская сессия, которую обязан обработать прогон этого слота.

    Слот 00:15 обрабатывает ПРЕДЫДУЩУЮ сессию: сессия текущих суток ещё не
    закрыта (market_time.last_closed_index). Конвенция сессии не дублируется —
    берётся из market_time через MSK.
    """
    return (slot_at.astimezone(MSK) - timedelta(days=1)).date()
