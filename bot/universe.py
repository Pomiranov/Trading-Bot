_SAMPLE_NS = "sample-start:"


def sample_version(start: date) -> str:
    """Отпечаток окна выборки: sha256[:16] от ISO-даты начала с префиксом.

    Префикс `_SAMPLE_NS` — не украшение. Без него `sample_version(date(2023,7,12))`
    и `universe_version(("2023-07-12",))` считают sha256 от ОДНОЙ И ТОЙ ЖЕ строки
    и дают одинаковый отпечаток: universe_version склеивает тикеры запятой, а для
    одного элемента склейка равна самому элементу. Совпадение обнаружено тестом
    30.07 при первой же попытке его проверить — до этого разделение пространств
    было заявлено в докстринге и не реализовано.

    Безвредно оно ровно до дня, когда кто-то сравнит отпечаток набора с отпечатком
    окна напрямую и получит «совпало» там, где сущности разные.
    """
    return hashlib.sha256(
        (_SAMPLE_NS + start.isoformat()).encode("utf-8")).hexdigest()[:16]


SAMPLE_START_2026_07_VERSION = sample_version(SAMPLE_START_2026_07)


def describe(name: str, tickers: tuple[str, ...]) -> str:
    """Строка для шапки прогона: имя набора, размер, отпечаток."""
    return f"{name}: {len(tickers)} бумаг, отпечаток {universe_version(tickers)}"


def describe_sample(start: date) -> str:
    """Строка для шапки прогона: окно выборки и его отпечаток."""
    return f"окно выборки: с {start.isoformat()}, отпечаток {sample_version(start)}"
